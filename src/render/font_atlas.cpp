const FontGlyph *FindFontGlyph(const FontTable &table, uint32_t codepoint)
{
    for (int i = 0; i < table.count; ++i) {
        if (table.glyphs[i].codepoint == codepoint) {
            return &table.glyphs[i];
        }
    }
    return nullptr;
}

int MeasureFontText(const FontTable &table, const char *utf8)
{
    int width = 0;
    for (const char *p = utf8; p != nullptr && *p != 0;) {
        const uint32_t cp = DecodeUtf8(&p);
        const FontGlyph *glyph = FindFontGlyph(table, cp);
        width += glyph != nullptr ? glyph->advance : FONT_UNKNOWN_ADVANCE;
    }
    return width;
}

